#!/usr/bin/env node
// Generates plugins/botreeve/ from the botreeve MCP server's own sources, so the
// plugin can never drift from the tools the server registers.
//
//   node scripts/generate.mjs --source <botreeve checkout>          write
//   node scripts/generate.mjs --source <botreeve checkout> --check  exit 1 if stale
//   node scripts/generate.mjs --source <...> --zip dist/botreeve.zip  also zip the plugin
//
// Inputs (read-only): <source>/docs/mcp/catalog.json (generated from the server's
// tools/list, checked by botreeve CI) and <source>/skills/botreeve-mcp/SKILL.md
// (the authored companion skill, checked against that catalog by botreeve CI).
// Output: plugins/botreeve/{.claude-plugin/plugin.json,.mcp.json,README.md,skills/botreeve-mcp/**}.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'plugins', 'botreeve');
const SKILL_NAME = 'botreeve-mcp';
const GENERATED = 'GENERATED by scripts/generate.mjs from the botreeve repo (docs/mcp, skills/botreeve-mcp). Do not edit.';

function fail(message) {
  console.error(`generate: ${message}`);
  process.exit(1);
}

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const source = arg('--source');
const check = process.argv.includes('--check');
const zipTo = arg('--zip');
if (!source) {
  fail('--source <botreeve checkout> is required');
}
const catalogPath = path.join(source, 'docs', 'mcp', 'catalog.json');
const skillPath = path.join(source, 'skills', SKILL_NAME, 'SKILL.md');
for (const p of [catalogPath, skillPath]) {
  if (!fs.existsSync(p)) {
    fail(`missing input: ${p}`);
  }
}

const catalogRaw = fs.readFileSync(catalogPath);
const catalog = JSON.parse(catalogRaw.toString('utf8'));
if (typeof catalog.endpoint !== 'string' || !Array.isArray(catalog.tools)) {
  fail('catalog.json lacks endpoint/tools');
}
const SERVER_URL = catalog.endpoint;
const catalogHash = crypto.createHash('sha256').update(catalogRaw).digest('hex').slice(0, 12);
const tools = catalog.tools;
const toolCount = tools.length;

const files = new Map();

// The authored skill: stamped with what it was checked against, and with the
// repo-internal file pointers (meaningless inside a plugin) pointed at this bundle.
const skillKey = path.join('skills', SKILL_NAME, 'SKILL.md');
let skill = fs.readFileSync(skillPath, 'utf8');
function swap(from, to) {
  if (!skill.includes(from)) {
    fail(`SKILL.md no longer contains ${JSON.stringify(from)}; update scripts/generate.mjs`);
  }
  skill = skill.replace(from, to);
}
swap('(docs/openapi.yaml)', '(the botreeve apps\' own API)');
swap('The tool catalog is `docs/mcp/catalog.json`, generated from the\nserver\'s own `tools/list`; this skill is checked against it in CI.',
  'The tool catalog, generated from the server\'s own `tools/list`, is in\n[references/tool-catalog.md](references/tool-catalog.md); this skill is checked against it in CI.');
const lines = skill.split('\n');
if (lines[0] !== '---') {
  fail('SKILL.md has no frontmatter');
}
const end = lines.indexOf('---', 1);
lines.splice(end, 0,
  'metadata:',
  `  tool_count: "${toolCount}"`,
  `  catalog_hash: "${catalogHash}"`,
  `  server_url: "${SERVER_URL}"`);
files.set(skillKey, lines.join('\n'));

// The full tool list, rendered from the catalog.
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const firstSentence = (s) => esc(s).split(/(?<=\.)\s/)[0].replace(/\bpass (?=\w)/g, 'give ');
const rows = [...tools].sort((a, b) => a.name.localeCompare(b.name)).map((t) => {
  const required = (t.inputSchema && t.inputSchema.required) || [];
  return `| \`${t.name}\` | ${required.map((r) => `\`${r}\``).join(', ') || '-'} | ${firstSentence(t.description)} |`;
});
files.set(path.join('skills', SKILL_NAME, 'references', 'tool-catalog.md'), [
  `<!-- ${GENERATED} -->`,
  '# botreeve tool catalog',
  '',
  `${toolCount} tools on \`${SERVER_URL}\` (catalog \`${catalogHash}\`). The connected server's own tool list always wins over this file.`,
  '',
  '| Tool | Required arguments | What it does |',
  '|---|---|---|',
  ...rows,
  '',
].join('\n'));

files.set(path.join('.claude-plugin', 'plugin.json'), JSON.stringify({
  name: 'botreeve',
  version: `1.0.0+${catalogHash}`,
  description: 'botreeve in Claude: join a botreeve group as a bot, post and read group messages, answer questions, run polls, notes and to-do lists, and ask other bots, through the botreeve MCP connector.',
  author: { name: 'botreeve', url: 'https://botreeve.ai' },
  homepage: 'https://botreeve.ai',
  privacyPolicyUrl: 'https://botreeve.ai/legal/privacy',
  repository: 'https://github.com/GutenGroup/botreeve-claude-plugin',
  license: 'MIT',
  keywords: ['botreeve', 'mcp', 'bots', 'groups', 'messaging', 'agents'],
}, null, 2) + '\n');

files.set('README.md', [
  `<!-- ${GENERATED} -->`,
  '# botreeve',
  '',
  'botreeve in Claude. Installs the botreeve connector (`' + SERVER_URL + '`) and the botreeve-mcp skill. You sign in to botreeve once, the first time Claude uses the connector, and choose the group and the bot Claude speaks as.',
  '',
  'Install: `claude plugin marketplace add GutenGroup/botreeve-claude-plugin`, then `claude plugin install botreeve@botreeve`.',
  '',
  '- Website: https://botreeve.ai',
  '- Privacy: https://botreeve.ai/legal/privacy',
  '- Terms: https://botreeve.ai/legal/terms',
  '',
].join('\n'));

// The listing icon: the botreeve app icon (botreeve repo docs/store/assets/icon/play-icon-512.png).
files.set(path.join('.claude-plugin', 'icon.png'), fs.readFileSync(path.join(ROOT, 'assets', 'icon.png')));

files.set('.mcp.json', JSON.stringify({
  mcpServers: { botreeve: { type: 'http', url: SERVER_URL } },
}, null, 2) + '\n');

function listExisting(dir, rel = '') {
  if (!fs.existsSync(dir)) {
    return [];
  }
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const r = path.join(rel, e.name);
    if (e.isDirectory()) {
      out.push(...listExisting(path.join(dir, e.name), r));
    } else {
      out.push(r);
    }
  }
  return out;
}

if (check) {
  const stale = [];
  for (const [rel, content] of files) {
    const p = path.join(OUT, rel);
    if (!fs.existsSync(p) || !fs.readFileSync(p).equals(Buffer.from(content))) {
      stale.push(rel);
    }
  }
  for (const rel of listExisting(OUT)) {
    if (!files.has(rel)) {
      stale.push(`${rel} (not generated)`);
    }
  }
  if (stale.length) {
    console.error(`plugin is stale against catalog ${catalogHash}:\n  ${stale.join('\n  ')}`);
    console.error('Run: node scripts/generate.mjs --source <botreeve checkout>  and commit.');
    process.exit(1);
  }
  console.log(`plugin is current (${toolCount} tools, catalog ${catalogHash})`);
} else {
  fs.rmSync(OUT, { recursive: true, force: true });
  for (const [rel, content] of files) {
    const p = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
  console.log(`wrote ${files.size} files (${toolCount} tools, catalog ${catalogHash})`);
}

if (zipTo) {
  const dest = path.resolve(zipTo);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.rmSync(dest, { force: true });
  execFileSync('zip', ['-qrX', dest, '.'], { cwd: OUT });
  console.log(`zipped ${dest}`);
}
